#!/usr/bin/env python3
"""雪山底图调冷：逐色族定向重映射（纯色值替换，像素位置不动 → 硬边像素不受影响）。

为什么不用「全局加蓝滤镜」：
  · 松树绿 #406040/#608060 的 R=B 相等，本身中性；全局加蓝会把它们染成青。
  · 把奶油黄 #E0E0C0 往冷锚点混只会得到"灰雪"（中性），不会读成"冷雪"。
    雪要显冷，关键是让 B 抬到 R 之上（或 R 降到 G 之下），必须逐族指定目标色。
所以：雪/山/霜青/暖棕/描边各给目标色，绿系只做极轻冷化。

幂等：表里同时写入「旧色→新色」和「新色→新色」，可反复运行不会二次偏色。

用法：python tools/make_snow_cool.py [图片路径]
默认：assets/snow_mountain/snow_mountain_concept_pixel_1024.png
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT / "assets/snow_mountain/snow_mountain_concept_pixel_1024.png"

# 源色 -> 目标色，按色族分组。
MAP = {
    # ---- 雪：奶油黄 → 冷白（蓝抬到 R 之上，才读得出"冷"）----
    (224, 224, 192): (226, 236, 244),   # #E0E0C0 主雪面 60.5%
    (224, 224, 224): (232, 240, 246),   # 最亮雪
    (192, 192, 192): (198, 212, 224),   # 浅中性
    (160, 192, 192): (166, 198, 210),   # 雪中调 / 亮天空
    (160, 192, 160): (156, 194, 192),   # 过渡色，去绿偏
    (192, 224, 192): (198, 228, 232),

    # ---- 霜青 / 冷蓝：略偏蓝（贴近城镇霜青 #7FA8A0 但更冷）----
    (128, 160, 160): (124, 168, 176),   # #80A0A0 天空 / 霜面 9.5%
    (128, 128, 160): (128, 152, 180),
    (64, 96, 96): (62, 100, 112),
    (96, 128, 128): (92, 140, 150),
    (32, 64, 64): (30, 68, 80),

    # ---- 山体 / 岩石：橄榄 → 冷板岩（黄偏第二大来源）----
    (128, 128, 96): (122, 138, 150),    # #808060 橄榄 2.9%
    (96, 96, 64): (82, 95, 108),        # #606040 暗橄榄 2.6%
    (64, 64, 32): (60, 69, 82),
    (96, 96, 96): (90, 102, 112),       # 中岩
    (64, 64, 64): (62, 70, 78),         # 暗岩
    (128, 128, 128): (122, 136, 148),
    (160, 160, 160): (156, 170, 182),
    (160, 160, 128): (154, 164, 168),
    (192, 192, 160): (196, 206, 216),   # #C0C0A0 淡黄 → 冷浅灰
    (224, 224, 160): (228, 234, 232),   # #E0E0A0 亮黄 → 冷白

    # ---- 松树绿：保留绿相，只做极轻冷化（不能变青）----
    (64, 96, 64): (62, 98, 80),
    (96, 128, 96): (90, 136, 116),
    (32, 64, 32): (28, 64, 56),
    (128, 160, 128): (124, 164, 132),
    (96, 128, 64): (92, 128, 98),
    (32, 96, 64): (30, 96, 82),
    (96, 160, 128): (92, 160, 138),
    (0, 32, 0): (10, 40, 32),

    # ---- 描边 / 极暗：→ 冷黑（#202000 这类暖黑残渣一并修正）----
    (32, 32, 32): (28, 34, 42),
    (32, 32, 0): (28, 36, 46),
    (32, 0, 0): (32, 34, 46),
    (32, 0, 32): (32, 32, 56),
    (0, 0, 0): (0, 0, 0),
    (64, 32, 32): (58, 46, 52),
    (64, 64, 96): (58, 70, 96),

    # ---- 暖棕（树皮/零星暖调）：→ 中性冷棕，保住暖冷对比但不泛黄 ----
    (96, 64, 64): (90, 74, 76),
    (128, 96, 96): (122, 106, 108),
    (160, 128, 128): (154, 140, 142),
    (192, 160, 160): (186, 174, 180),
    (224, 192, 192): (220, 226, 234),
}

# 幂等：目标色再映射到自身
for _v in list(MAP.values()):
    MAP.setdefault(_v, _v)


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT
    im = Image.open(src).convert("RGB")
    src_colors = set(im.getdata())

    missing = src_colors - set(MAP)
    if missing:
        raise SystemExit("有 %d 个源色未指定目标色：%s" % (len(missing), sorted(missing)))

    lut = {c: MAP[c] for c in src_colors}
    out = Image.new("RGB", im.size)
    out.putdata([lut[c] for c in im.getdata()])
    out.save(src)

    px = out.load()
    W, H = out.size
    tot = [0, 0, 0]
    n = 0
    for y in range(0, H, 2):
        for x in range(0, W, 2):
            c = px[x, y]
            tot[0] += c[0]; tot[1] += c[1]; tot[2] += c[2]
            n += 1
    print("调冷 -> %s" % src.name)
    print("均值 RGB :", [round(t / n) for t in tot])
    print("R-B      :", round((tot[0] - tot[2]) / n, 1), "(负=偏冷)")
    print("唯一色数 :", len(set(out.getdata())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
